// Builds the clayo landing page from src/landing.html into:
//   preview/index.html                       – standalone page with sample data
//   shopify/sections/clayo-landing.liquid    – Shopify OS 2.0 section bound to a product
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';

const src = readFileSync('src/landing.html', 'utf8');
const fonts =
  '<link rel="preconnect" href="https://fonts.googleapis.com">\n' +
  '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n' +
  '<link href="https://fonts.googleapis.com/css2?family=Poppins:wght@400;500;600;700&display=swap" rel="stylesheet">\n';

const fill = (tokens) => src.replace(/__([A-Z_]+)__/g, (m, k) => (k in tokens ? tokens[k] : m));

// ---- Preview ----
const preview = fill({
  PRICE: '$49',
  COMPARE_BLOCK: '<s>$79</s><span class="c-save">Save $30</span>',
  VARIANT_ID: '0',
  HERO_IMG: '../assets/clayo-hero.webp',
  DETAIL_IMG: '../assets/clayo-hero.webp',
  CTA_LABEL: 'Add to cart',
  CTA_ATTR: '',
  RATING_TEXT: '4.8 / 5 average rating',
  FREE_SHIP: '$50',
});
mkdirSync('preview', { recursive: true });
writeFileSync(
  'preview/index.html',
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>clayo — Warmth Belt</title>
${fonts}<style>html{scroll-behavior:smooth}body{margin:0;background:#FFFFFF}</style>
</head>
<body>
${preview}
</body>
</html>
`
);

// ---- Shopify section ----
const money = (expr) => `{{ ${expr} | money_without_trailing_zeros }}`;
const liquid = fill({
  PRICE: money('p.price'),
  COMPARE_BLOCK:
    `{%- if p.compare_at_price > p.price -%}<s>${money('p.compare_at_price')}</s>` +
    `<span class="c-save">Save {{ p.compare_at_price | minus: p.price | money_without_trailing_zeros }}</span>{%- endif -%}`,
  VARIANT_ID: '{{ p.selected_or_first_available_variant.id }}',
  HERO_IMG:
    '{%- if section.settings.hero_image != blank -%}{{ section.settings.hero_image | image_url: width: 1400 }}' +
    '{%- elsif p.featured_image != blank -%}{{ p.featured_image | image_url: width: 1400 }}' +
    "{%- else -%}{{ 'clayo-hero.webp' | asset_url }}{%- endif -%}",
  // The detail hotspots are positioned for this exact photo, so it always uses the bundled asset.
  DETAIL_IMG: "{{ 'clayo-hero.webp' | asset_url }}",
  CTA_LABEL:
    '{%- if p.selected_or_first_available_variant.available -%}Add to cart{%- else -%}Sold out{%- endif -%}',
  CTA_ATTR: '{% unless p.selected_or_first_available_variant.available %}disabled{% endunless %}',
  RATING_TEXT: '{{ section.settings.rating_text | escape }}',
  FREE_SHIP: '{{ section.settings.free_shipping | escape }}',
});

const schema = {
  name: 'clayo landing',
  tag: 'section',
  class: 'clayo-landing',
  settings: [
    { type: 'product', id: 'product', label: 'Product', info: 'Defaults to the current product on product templates.' },
    { type: 'image_picker', id: 'hero_image', label: 'Hero image', info: "Defaults to the product's featured image." },
    { type: 'text', id: 'rating_text', label: 'Rating text', default: '4.8 / 5 average rating' },
    { type: 'text', id: 'free_shipping', label: 'Free shipping threshold', default: '$50' },
  ],
  presets: [{ name: 'clayo landing' }],
};

mkdirSync('shopify/sections', { recursive: true });
mkdirSync('shopify/assets', { recursive: true });
writeFileSync(
  'shopify/sections/clayo-landing.liquid',
  `{%- comment -%} Generated by build.mjs from src/landing.html — edit the source, not this file. {%- endcomment -%}
{%- liquid
  assign p = product
  if section.settings.product != blank
    assign p = section.settings.product
  endif
-%}
${fonts}${liquid}
{% schema %}
${JSON.stringify(schema, null, 2)}
{% endschema %}
`
);
copyFileSync('assets/clayo-hero.webp', 'shopify/assets/clayo-hero.webp');
console.log('Built preview/index.html and shopify/sections/clayo-landing.liquid');
